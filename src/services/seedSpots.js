export async function seedSpots() {
  try {
    console.log("Checking Firestore connection...");

    // Try writing first spot to verify permissions
    const testRef = await addDoc(collection(db, "spots"), {
      ...SEED_SPOTS[0],
      createdAt: serverTimestamp(),
    });

    console.log("✅ Permissions OK! Seeding remaining spots...");

    // Seed the rest
    for (let i = 1; i < SEED_SPOTS.length; i++) {
      await addDoc(collection(db, "spots"), {
        ...SEED_SPOTS[i],
        createdAt: serverTimestamp(),
      });
      console.log("✅ Seeded:", SEED_SPOTS[i].name);
    }

    console.log("🎉 All", SEED_SPOTS.length, "spots seeded successfully!");
    return true;
  } catch (err) {
    console.error("Seed error:", err.message);
    return false;
  }
}